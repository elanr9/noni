/** Glyphs missing from the table (emoji, other scripts) use this width. */
export const TIKTOK_SANS_FALLBACK_WIDTH: Readonly<Record<OverlayFont, number>> = {
  bubble: 0.58,
  condensed: 0.58,
};

export function measureOverlayLine(text: string, font: OverlayFont): number {
  const widths = TIKTOK_SANS_BUBBLE_WIDTHS;
  let total = 0;
  for (const ch of text) {
    total += widths[ch] ?? TIKTOK_SANS_FALLBACK_WIDTH[font];
  }
  return total;
}

/**
 * Greedy word wrap in em units. Explicit newlines are hard breaks and words
 * longer than the line are split by character, exactly as the render does.
 */
export function wrapOverlayLines(text: string, maxWidthEm: number, font: OverlayFont): string[] {
  const out: string[] = [];
  for (const paragraph of text.split("\n")) {
    const words = paragraph.trim().split(/\s+/).filter((w) => w.length > 0);
    if (words.length === 0) {
      out.push("");
      continue;
    }
    let line = "";
    for (const word of words) {
      const candidate = line.length === 0 ? word : `${line} ${word}`;
      if (measureOverlayLine(candidate, font) <= maxWidthEm) {
        line = candidate;
        continue;
      }
      if (line.length > 0) out.push(line);
      line = "";
      let chunk = "";
      for (const ch of word) {
        if (measureOverlayLine(chunk + ch, font) > maxWidthEm && chunk.length > 0) {
          out.push(chunk);
          chunk = "";
        }
        chunk += ch;
      }
      line = chunk;
    }
    if (line.length > 0) out.push(line);
  }
  return out;
}
